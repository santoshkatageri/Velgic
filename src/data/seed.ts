const DAY = 86_400_000
// Seed dates are anchored around "today" (2026-08-17) so "x days ago" reads naturally.
const now = new Date('2026-08-17T09:00:00Z').getTime()
const iso = (daysAgo: number) => new Date(now - daysAgo * DAY).toISOString()

const cl = (label: string, done: boolean): ChecklistItem => ({ id: label, label, done })

function item(partial: Partial<Item> & Pick<Item, 'id' | 'title' | 'category' | 'format'>): Item {
  const scores: ScoreSet = {
    audienceValue: partial.scores?.audienceValue ?? 7,
    novelty: partial.scores?.novelty ?? 7,
    personalRelevance: partial.scores?.personalRelevance ?? 7,
    easeOfExecution: partial.scores?.easeOfExecution ?? 6,
  }
  return {
    problem: '',
    audience: 'Developers',
    estimatedEffort: 3,
    potentialImpact: 7,
    reusable: false,
    stage: 'ideas',
    priority: 'medium',
    notes: '',
    coreIdea: '',
    hook: '',
    audienceProblem: '',
    keyInsight: '',
    script: '',
    visualPlan: '',
    productionNotes: '',
    linkedInPost: '',
    instagramCaption: '',
    checklist: [],
    performance: null,
    lessonsLearned: '',
    createdAt: iso(30),
    updatedAt: iso(30),
    ...partial,
    scores,
  }
}

